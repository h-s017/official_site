// Keep the existing core/global cascade, but deliver it before first paint.
import fs from 'node:fs';
const core=fs.readFileSync('assets/site-core.js','utf8');
const site=fs.readFileSync('assets/site.js','utf8');
const coreCSS=core.match(/const style = document\.createElement\("style"\);\s*style\.textContent = `([\s\S]*?)`;/)?.[1];
const globalCSS=site.match(/style\.id = "hana-global-20260910";\s*style\.textContent = `([\s\S]*?)`;/)?.[1];
if(!coreCSS||!globalCSS||coreCSS.includes('${')||globalCSS.includes('${'))throw Error('Expected static CSS templates');
const rawCSS='/* Generated by scripts/build-runtime-layout.mjs; same core then global cascade as the JS fallback. */\n'+coreCSS+'\n'+globalCSS+'\n';
const css=rawCSS.split('\n').map(line=>line.trimEnd()).join('\n').trimEnd()+'\n';
if(process.argv.includes('--check')){if(fs.readFileSync('assets/runtime-layout.css','utf8')!==css)throw Error('Run scripts/build-runtime-layout.mjs');}
else fs.writeFileSync('assets/runtime-layout.css',css);
